// Writes UwUFiles' brand SVGs from the suite's Nyu catalogue (docs/app-icons.md in
// @uwusuite/design): Nyu as the box, on the pastel tile, with a folder, a heart and a sparkle.
//
//   node scripts/brand.mjs        (then `pnpm icons` makes the platform files)
//
// Nyu has no "files" shell of her own yet; the box (she keeps things) stands in until one
// goes into the package.

import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(root, 'apps/desktop/package.json'));
const pkg = dirname(require.resolve('@uwusuite/design/package.json'));
const { nyuSvg } = await import(pathToFileURL(join(pkg, 'dist/nyu/svg.js')).href);

const EDGE_STYLE =
  '<style>.nyu-edge,.nyu-edge *{fill:#fff;stroke:#fff}.nyu-edge *{stroke-width:inherit}.nyu-edge [fill="none"],.nyu-edge [fill="none"] *{fill:none}.nyu-edge .no-edge{display:none}</style>';

// Nyu's inner SVG and her box, from the catalogue.
const nyu = nyuSvg({ shell: 'box', mood: 'uwu', blink: false, label: 'Nyu' });
const [vx, vy, vw, vh] = nyu.match(/viewBox="([^"]+)"/)[1].split(' ').map(Number);
const inner = nyu.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');

const PLUM = '#4B1D3F';
const folder = (x, y, s, r) => `
  <g transform="translate(${x} ${y}) rotate(${r}) scale(${s})" stroke-linejoin="round" stroke-linecap="round">
    <g fill="#fff" stroke="#fff" stroke-width="22"><path d="M-46 -30 H-14 L-4 -20 H46 V30 H-46 Z"/></g>
    <path d="M-46 -30 H-14 L-4 -20 H46 V30 H-46 Z" fill="#FFD66E" stroke="${PLUM}" stroke-width="8"/>
    <path d="M-46 -12 H46 V30 H-46 Z" fill="#FFE59A" stroke="${PLUM}" stroke-width="8"/>
  </g>`;
const heart = (x, y, s) => `
  <g transform="translate(${x} ${y}) scale(${s})" stroke-linejoin="round">
    <path d="M0 18 C-30 -2 -24 -26 -8 -24 C-3 -23 0 -19 0 -15 C0 -19 3 -23 8 -24 C24 -26 30 -2 0 18 Z" fill="#fff" stroke="#fff" stroke-width="16"/>
    <path d="M0 18 C-30 -2 -24 -26 -8 -24 C-3 -23 0 -19 0 -15 C0 -19 3 -23 8 -24 C24 -26 30 -2 0 18 Z" fill="#FF6FA6" stroke="${PLUM}" stroke-width="6"/>
  </g>`;
const sparkle = (x, y, s) => `
  <g transform="translate(${x} ${y}) scale(${s})" stroke-linejoin="round">
    <path d="M0 -26 Q4 -4 26 0 Q4 4 0 26 Q-4 4 -26 0 Q-4 -4 0 -26 Z" fill="#fff" stroke="#fff" stroke-width="14"/>
    <path d="M0 -26 Q4 -4 26 0 Q4 4 0 26 Q-4 4 -26 0 Q-4 -4 0 -26 Z" fill="#FFD66E" stroke="${PLUM}" stroke-width="6"/>
  </g>`;

/** Nyu, `width` px wide, centred on (cx, cy), tilted by `tilt` degrees. */
const placed = (cx, cy, width, tilt) => {
  const s = width / vw;
  return `<g transform="translate(${cx} ${cy}) rotate(${tilt}) scale(${s}) translate(${-(vx + vw / 2)} ${-(vy + vh / 2)})">${inner}</g>`;
};

const svg = (label, body) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512" role="img" aria-label="${label}">
  <title>UwUFiles</title>
  <!-- Generated by scripts/brand.mjs from the @uwusuite/design Nyu catalogue. -->
  ${EDGE_STYLE}
  <defs>
    <linearGradient id="uwu-bg" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#FFF3F8"/><stop offset="1" stop-color="#FFD3E5"/></linearGradient>
    <filter id="uwu-shadow" x="-20%" y="-20%" width="140%" height="150%"><feDropShadow dx="0" dy="10" stdDeviation="10" flood-color="#C2306F" flood-opacity="0.25"/></filter>
  </defs>
  ${body}
</svg>
`;

const appIcon = svg(
  'UwUFiles app icon: Nyu as a box with cat ears, a folder, a heart and a sparkle',
  `<rect width="512" height="512" rx="116" fill="url(#uwu-bg)"/>
  <g filter="url(#uwu-shadow)">${placed(250, 282, 330, -7)}</g>
  ${folder(388, 372, 1.05, 8)}
  ${heart(112, 128, 1.1)}
  ${sparkle(398, 116, 1.15)}`,
);

const taskbar = svg('UwUFiles: a box with cat ears', `${placed(256, 262, 440, 0)}`);

writeFileSync(join(root, 'brand/uwufiles-app-icon.svg'), appIcon);
writeFileSync(join(root, 'brand/uwufiles-taskbar-icon.svg'), taskbar);
writeFileSync(join(root, 'brand/uwufiles-symbol.svg'), taskbar);
console.log('brand/uwufiles-{app-icon,taskbar-icon,symbol}.svg written');
